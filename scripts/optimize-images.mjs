import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

// Pass a folder containing PHOTO_*.jpg originals. These are the exact campaign
// photos formerly embedded in WarmHeartStore.jsx, not the older public JPGs.
const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/optimize-images.mjs <originals-folder>');
const names = ['HERO_FRONT', 'FLOCK_DETAIL', 'FEMALE_WALK', 'BACK_NECK', 'GROUP', 'HANGER'];
await mkdir('src/assets/campaign', { recursive: true });
let module = '// Generated by scripts/optimize-images.mjs\n';
const entries = [];
for (const name of names) {
  const input = path.join(source, `PHOTO_${name}.jpg`);
  const { width, height } = await sharp(input).rotate().metadata();
  const variants = [];
  for (const size of [480, 960, 1440].filter(size => size <= width)) {
    const file = `${name.toLowerCase()}-${size}.webp`;
    await sharp(input).rotate().resize({ width: size, withoutEnlargement: true })
      .webp({ quality: 82, effort: 6 }).toFile(`src/assets/campaign/${file}`);
    const id = `${name}_${size}`;
    module += `import ${id} from './assets/campaign/${file}';\n`;
    variants.push({ size, id });
  }
  const fallback = variants.find(v => v.size === 960) || variants.at(-1);
  module += `export const PHOTO_${name} = ${fallback.id};\n`;
  entries.push(`[PHOTO_${name}]: { width: ${width}, height: ${height}, srcSet: [${variants.map(v => `${v.id} + ' ${v.size}w'`).join(', ')}].join(', ') }`);
}
module += `export const IMAGE_VARIANTS = {\n  ${entries.join(',\n  ')}\n};\n`;
await writeFile('src/campaign-images.js', module);
